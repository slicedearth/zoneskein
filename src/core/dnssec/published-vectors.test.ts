function base64(value: string): Uint8Array {
  const binary = atob(value.replaceAll(/\s/gu, ''));
  return Uint8Array.from(binary, (character) => character.charCodeAt(0));
}

function concatenate(...parts: readonly Uint8Array[]): Uint8Array {
  const length = parts.reduce((total, part) => total + part.length, 0);
  const output = new Uint8Array(length);
  let offset = 0;
  for (const part of parts) {
    output.set(part, offset);
    offset += part.length;
  }
  return output;
}

interface PublishedSignatureVector {
  readonly algorithm: 5 | 7 | 8 | 10 | 13 | 14 | 15;
  readonly expectedSignedData: string;
  readonly flags: 256 | 257;
  readonly keyTag: number;
  readonly label: string;
  readonly owner: string;
  readonly publicKey: string;
  readonly signature: string;
}

